// Publish every source occurrence. Repetition metadata never removes vocabulary.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { prepare } = require('../vocabulary.js');
const root = path.resolve(__dirname, '..'), context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'data/source-words.js'), 'utf8'), context);
const data = prepare(context.window.VOCABULARY);
fs.writeFileSync(path.join(root, 'data/words.js'), '// Generated by scripts/build_vocabulary.cjs; all printed occurrences retained.\nwindow.VOCABULARY = ' + JSON.stringify(data, null, 2) + ';\n');
console.log(`Published all ${data.words.length} occurrences; none omitted.`);
