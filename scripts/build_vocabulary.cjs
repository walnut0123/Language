// Publish already-curated data: the browser never receives duplicate source entries.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { prepare } = require('../vocabulary.js');
const root = path.resolve(__dirname, '..'), context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'data/source-words.js'), 'utf8'), context);
const data = prepare(context.window.VOCABULARY);
fs.writeFileSync(path.join(root, 'data/words.js'), '// Generated by scripts/build_vocabulary.cjs from source-words.js. Keep permanent IDs intact.\nwindow.VOCABULARY = ' + JSON.stringify(data, null, 2) + ';\n');
console.log(`Published ${data.words.length} words; ${Object.keys(data.duplicateOf).length} exact duplicates omitted.`);
